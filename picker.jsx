export default function DietChallengePicker() {
  const [name, setName] = useState("");
  const [result, setResult] = useState("");

  const pickChallenge = () => {
    if (!name.trim()) return;
    const randomIndex = Math.floor(Math.random() * challenges.length);
    setResult(`${name}님의 오늘의 챌린지는: \n${challenges[randomIndex]}`);
  };

  return (
    <div style={{ padding: 20, fontFamily: 'sans-serif' }}>
      <h1>🎲 오늘의 식단 챌린지 뽑기</h1>
      <input
        type="text"
        placeholder="이름을 입력하세요"
        value={name}
        onChange={(e) => setName(e.target.value)}
      />
      <button onClick={pickChallenge} style={{ marginLeft: 10 }}>챌린지 뽑기!</button>
      {result && (
        <div style={{ marginTop: 20, padding: 10, background: '#def', borderRadius: 5 }}>
          <pre>{result}</pre>
        </div>
      )}
    </div>
  );
}